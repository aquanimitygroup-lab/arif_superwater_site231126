// Reads public/index.html and writes lib/cms-defaults.js: the text the page shows
// today for every editable field. Run after editing public/index.html by hand:
//   node scripts/extract-defaults.js
import { readFileSync, writeFileSync } from 'node:fs';
import { CMS_FIELDS, NON_PAGE_DEFAULTS } from '../lib/cms-schema.js';

const root = new URL('..', import.meta.url);
const html = readFileSync(new URL('public/index.html', root), 'utf8');

const decode = (t) => t
  .replace(/<br\s*\/?>/g, ' ')
  .replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/\s+/g, ' ').trim();

const out = {};

// 1. Elements tagged data-cms="key" (innermost text, no nested tags expected).
const re = /<([a-z0-9]+)\b[^>]*\sdata-cms="([^"]+)"[^>]*>([\s\S]*?)<\/\1>/g;
for (const m of html.matchAll(re)) {
  if (out[m[2]] !== undefined) throw new Error(`data-cms="${m[2]}" appears more than once`);
  out[m[2]] = decode(m[3]);
}

// 2. The scrolling strip: first copy of its items.
const track = html.match(/data-cms-lines="marquee\.items">([\s\S]*?)<\/div>/)[1];
const items = [...track.split('\n').find((l) => l.includes('<span>')).matchAll(/<span>([^<]*)<\/span>/g)].map((m) => decode(m[1]));
out['marquee.items'] = items.join('\n');

// 3. Shop cards: the PLANS object in the page script.
const plansSrc = html.match(/const PLANS = (\{[\s\S]*?\n\});/)[1];
const PLANS = Function(`return (${plansSrc})`)();
for (const list of Object.values(PLANS)) {
  for (const p of list) {
    out[`plans.${p.sku}.title`] = p.title;
    out[`plans.${p.sku}.sub`] = p.sub;
    out[`plans.${p.sku}.badge`] = p.badge || '';
    out[`plans.${p.sku}.bullet1`] = p.bullets[0] || '';
    out[`plans.${p.sku}.bullet2`] = p.bullets[1] || '';
    out[`plans.${p.sku}.button`] = p.btn;
  }
}

Object.assign(out, NON_PAGE_DEFAULTS);

const missing = Object.keys(CMS_FIELDS).filter((k) => out[k] === undefined);
const unknown = Object.keys(out).filter((k) => !CMS_FIELDS[k]);
if (missing.length) throw new Error(`Editable fields not found on the page: ${missing.join(', ')}`);
if (unknown.length) throw new Error(`Tagged on the page but not in lib/cms-schema.js: ${unknown.join(', ')}`);

writeFileSync(new URL('lib/cms-defaults.js', root), '// Generated by scripts/extract-defaults.js from public/index.html. Do not edit by hand.\nexport default ' + JSON.stringify(out, null, 2) + ';\n');
console.log(`Wrote ${Object.keys(out).length} default values to lib/cms-defaults.js`);
